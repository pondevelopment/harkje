/* Prebuild script: writes src/environments/build-info.ts with version + git SHA + ISO time. */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

let sha = null;
let time = new Date().toISOString();
let version = null;
try {
  const pkg = JSON.parse(
    readFileSync(new URL('../package.json', import.meta.url), { encoding: 'utf8' }),
  );
  version = typeof pkg.version === 'string' && pkg.version ? pkg.version : null;
} catch {
  /* no readable package.json */
}
try {
  sha = execSync('git rev-parse HEAD', { encoding: 'utf8' }).trim() || null;
} catch {
  /* no git or not a repo */
}

const body = `/* Auto-generated by scripts/generate-build-info.mjs — do not edit. */
export const BUILD_VERSION: string | null = ${version ? JSON.stringify(version) : 'null'};
export const BUILD_SHA: string | null = ${sha ? JSON.stringify(sha) : 'null'};
export const BUILD_TIME: string | null = ${JSON.stringify(time)};
`;

writeFileSync(new URL('../src/environments/build-info.ts', import.meta.url), body);
console.log('[harkje] build-info: version=%s sha=%s time=%s', version, sha, time);
